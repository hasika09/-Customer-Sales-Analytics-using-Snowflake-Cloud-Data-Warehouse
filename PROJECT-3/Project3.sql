INSERT INTO SALES
(
    SALE_ID,
    CUSTOMER_ID,
    PRODUCT_ID,
    BRANCH_ID,
    QUANTITY,
    SALE_DATE,
    TOTAL_AMOUNT
)
SELECT
    SALE_ID,
    CUSTOMER_ID,
    PRODUCT_ID,
    BRANCH_ID,
    QUANTITY,
    SALE_DATE,
    TOTAL_AMOUNT
FROM NEW_SALES_STAGE;

SELECT
    SALE_ID,
    CUSTOMER_ID,
    PRODUCT_ID,
    BRANCH_ID,
    QUANTITY,
    SALE_DATE,
    TOTAL_AMOUNT,
    METADATA$ACTION,
    METADATA$ISUPDATE
FROM SALES_STREAM
WHERE METADATA$ACTION = 'INSERT'
ORDER BY SALE_ID;

MERGE INTO SALES AS TARGET
USING
(
    SELECT
        SALE_ID,
        CUSTOMER_ID,
        PRODUCT_ID,
        BRANCH_ID,
        QUANTITY,
        SALE_DATE,
        TOTAL_AMOUNT
    FROM NEW_SALES_STAGE
) AS SOURCE
ON TARGET.SALE_ID = SOURCE.SALE_ID

WHEN NOT MATCHED THEN

INSERT
(
    SALE_ID,
    CUSTOMER_ID,
    PRODUCT_ID,
    BRANCH_ID,
    QUANTITY,
    SALE_DATE,
    TOTAL_AMOUNT
)

VALUES
(
    SOURCE.SALE_ID,
    SOURCE.CUSTOMER_ID,
    SOURCE.PRODUCT_ID,
    SOURCE.BRANCH_ID,
    SOURCE.QUANTITY,
    SOURCE.SALE_DATE,
    SOURCE.TOTAL_AMOUNT
);

SELECT *
FROM SALES
ORDER BY SALE_ID;



