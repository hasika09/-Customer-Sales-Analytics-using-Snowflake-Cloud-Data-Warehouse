SELECT
    c.CUSTOMER_ID,
    c.CUSTOMER_NAME,
    COUNT(s.SALE_ID) AS PURCHASE_FREQUENCY
FROM CUSTOMERS c
JOIN SALES s
    ON c.CUSTOMER_ID = s.CUSTOMER_ID
GROUP BY
    c.CUSTOMER_ID,
    c.CUSTOMER_NAME
ORDER BY PURCHASE_FREQUENCY DESC;

SELECT
    SALE_DATE,
    SALE_ID,
    TOTAL_AMOUNT,
    SUM(TOTAL_AMOUNT) OVER (
        ORDER BY SALE_DATE, SALE_ID
        ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
    ) AS RUNNING_REVENUE
FROM SALES
ORDER BY SALE_DATE, SALE_ID;


SELECT
    c.CUSTOMER_ID,
    c.CUSTOMER_NAME,
    SUM(s.TOTAL_AMOUNT) AS TOTAL_REVENUE,

    RANK() OVER (
        ORDER BY SUM(s.TOTAL_AMOUNT) DESC
    ) AS CUSTOMER_RANK

FROM SALES s
JOIN CUSTOMERS c
    ON s.CUSTOMER_ID = c.CUSTOMER_ID

GROUP BY
    c.CUSTOMER_ID,
    c.CUSTOMER_NAME

ORDER BY CUSTOMER_RANK;


CREATE OR REPLACE VIEW CUSTOMER_REVENUE AS
SELECT
    c.CUSTOMER_ID,
    c.CUSTOMER_NAME,
    SUM(s.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM SALES s
JOIN CUSTOMERS c
    ON s.CUSTOMER_ID = c.CUSTOMER_ID
GROUP BY
    c.CUSTOMER_ID,
    c.CUSTOMER_NAME;


SELECT *
FROM CUSTOMER_REVENUE
ORDER BY TOTAL_REVENUE DESC;

CREATE OR REPLACE MATERIALIZED VIEW BRANCH_REVENUE AS
SELECT
    BRANCH_ID,
    SUM(TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM SALES
GROUP BY BRANCH_ID;


SELECT *
FROM BRANCH_REVENUE;

SELECT
    br.BRANCH_ID,
    b.BRANCH_NAME,
    br.TOTAL_REVENUE
FROM BRANCH_REVENUE br
JOIN BRANCHES b
    ON br.BRANCH_ID = b.BRANCH_ID
ORDER BY br.TOTAL_REVENUE DESC;