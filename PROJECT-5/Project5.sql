JOIN DIM_DATE D
    ON F.DATE_ID = D.DATE_ID
GROUP BY D.DATE
ORDER BY D.DATE;

SELECT
    F.SALE_ID,
    C.CUSTOMER_NAME,
    C.STATE AS CUSTOMER_STATE,
    P.PRODUCT_NAME,
    P.CATEGORY,
    P.BRAND,
    B.BRANCH_NAME,
    B.STATE AS BRANCH_STATE,
    B.REGION,
    D.DATE,
    D.MONTH,
    D.QUARTER,
    D.YEAR,
    F.QUANTITY,
    F.TOTAL_AMOUNT
FROM FACT_SALES F
JOIN DIM_CUSTOMER C
    ON F.CUSTOMER_ID = C.CUSTOMER_ID
JOIN DIM_PRODUCT P
    ON F.PRODUCT_ID = P.PRODUCT_ID
JOIN DIM_BRANCH B
    ON F.BRANCH_ID = B.BRANCH_ID
JOIN DIM_DATE D
    ON F.DATE_ID = D.DATE_ID
